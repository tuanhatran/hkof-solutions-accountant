-- Free additional charges attached to one rent receipt version. Rows are inserted with
-- the receipt and never updated or deleted: a new version carries its own rows.
CREATE TABLE rent_receipt_additional_charge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rent_receipt_id BIGINT NOT NULL REFERENCES rent_receipt (id),
    label VARCHAR(120) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    position INTEGER NOT NULL,
    CONSTRAINT ck_rent_receipt_additional_charge_amount CHECK (amount > 0)
);

CREATE INDEX ix_rent_receipt_additional_charge_receipt
    ON rent_receipt_additional_charge (rent_receipt_id, position);
