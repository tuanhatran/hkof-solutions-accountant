CREATE TABLE parametres (
    id BIGINT PRIMARY KEY,
    raison_sociale VARCHAR(255),
    forme_juridique VARCHAR(100),
    siren VARCHAR(20),
    societe_adresse VARCHAR(500),
    gerant VARCHAR(255),
    logement_adresse VARCHAR(500),
    surface_totale NUMERIC(8, 2),
    surface_pro NUMERIC(8, 2),
    bailleur_nom VARCHAR(255),
    bailleur_adresse VARCHAR(500),
    locataire_nom VARCHAR(255),
    locataire_adresse VARCHAR(500),
    loyer_hc NUMERIC(12, 2),
    provision_charges NUMERIC(12, 2),
    lieu_emission VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE poste (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    libelle VARCHAR(255) NOT NULL,
    fournisseur VARCHAR(255),
    prorata_pct NUMERIC(5, 2) NOT NULL,
    periodicite VARCHAR(20) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    ordre INTEGER NOT NULL,
    plusieurs_lignes_autorisees BOOLEAN NOT NULL DEFAULT FALSE,
    supprime BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_poste_prorata CHECK (prorata_pct >= 0 AND prorata_pct <= 100)
);

CREATE TABLE justificatif (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_fichier VARCHAR(255) NOT NULL,
    type_mime VARCHAR(120) NOT NULL,
    chemin VARCHAR(1000) NOT NULL,
    taille BIGINT NOT NULL,
    hash_sha256 VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    supprime BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE quittance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mois VARCHAR(7) NOT NULL,
    periode_debut DATE NOT NULL,
    periode_fin DATE NOT NULL,
    loyer_hc NUMERIC(12, 2) NOT NULL,
    charges NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    date_paiement DATE,
    date_emission DATE,
    version INTEGER NOT NULL,
    statut VARCHAR(20) NOT NULL,
    template_id BIGINT,
    template_nom VARCHAR(255),
    template_version INTEGER,
    chemin_pdf VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_quittance_mois_version UNIQUE (mois, version)
);
CREATE INDEX ix_quittance_mois ON quittance (mois);
CREATE UNIQUE INDEX ux_quittance_active ON quittance (mois) WHERE statut = 'ACTIVE';

CREATE TABLE note_frais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mois VARCHAR(7) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    version INTEGER NOT NULL,
    statut VARCHAR(20) NOT NULL,
    template_id BIGINT,
    template_nom VARCHAR(255),
    template_version INTEGER,
    chemin_pdf VARCHAR(1000),
    chemin_pdf_complet VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_note_frais_mois_version UNIQUE (mois, version)
);
CREATE INDEX ix_note_frais_mois ON note_frais (mois);
CREATE UNIQUE INDEX ux_note_frais_active ON note_frais (mois) WHERE statut = 'ACTIVE';

CREATE TABLE ligne_frais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_frais_id BIGINT NOT NULL REFERENCES note_frais (id) ON DELETE CASCADE,
    poste_id BIGINT NOT NULL REFERENCES poste (id),
    montant_ttc NUMERIC(12, 2) NOT NULL,
    periode_debut DATE,
    periode_fin DATE,
    montant_mois NUMERIC(12, 2) NOT NULL,
    prorata_pct NUMERIC(5, 2) NOT NULL,
    montant_retenu NUMERIC(12, 2) NOT NULL,
    justificatif_id BIGINT REFERENCES justificatif (id),
    source_montant VARCHAR(10) NOT NULL,
    montant_detecte_ia NUMERIC(12, 2),
    confiance_ia VARCHAR(20),
    libelle_snapshot VARCHAR(255),
    fournisseur_snapshot VARCHAR(255),
    CONSTRAINT ck_ligne_prorata CHECK (prorata_pct >= 0 AND prorata_pct <= 100),
    CONSTRAINT ck_ligne_montants CHECK (montant_ttc >= 0 AND montant_mois >= 0 AND montant_retenu >= 0)
);
CREATE INDEX ix_ligne_frais_note ON ligne_frais (note_frais_id);

CREATE TABLE analyse_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    justificatif_id BIGINT NOT NULL REFERENCES justificatif (id) ON DELETE CASCADE,
    statut VARCHAR(20) NOT NULL,
    modele VARCHAR(255),
    duree_ms BIGINT,
    resultat_json TEXT,
    message_erreur TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_analyse_justificatif ON analyse_document (justificatif_id);

CREATE TABLE llm_config (
    id BIGINT PRIMARY KEY,
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    fournisseur VARCHAR(20) NOT NULL,
    url VARCHAR(500) NOT NULL,
    modele VARCHAR(255),
    timeout_seconds INTEGER NOT NULL DEFAULT 120,
    temperature NUMERIC(3, 2) NOT NULL DEFAULT 0,
    num_ctx INTEGER NOT NULL DEFAULT 8192,
    pages_max INTEGER NOT NULL DEFAULT 5,
    ocr_actif BOOLEAN NOT NULL DEFAULT FALSE,
    prompt_extraction TEXT NOT NULL,
    cle_api TEXT,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE template_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    nom VARCHAR(255) NOT NULL,
    version INTEGER NOT NULL,
    format VARCHAR(10) NOT NULL,
    chemin VARCHAR(1000) NOT NULL,
    actif BOOLEAN NOT NULL DEFAULT FALSE,
    integre BOOLEAN NOT NULL DEFAULT FALSE,
    supprime BOOLEAN NOT NULL DEFAULT FALSE,
    rapport_validation TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_template_type ON template_document (type);
CREATE UNIQUE INDEX ux_template_actif ON template_document (type) WHERE actif AND NOT supprime;
