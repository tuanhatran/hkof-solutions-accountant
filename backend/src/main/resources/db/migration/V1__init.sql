CREATE TABLE settings (
    id BIGINT PRIMARY KEY,
    company_name VARCHAR(255),
    legal_form VARCHAR(100),
    siren VARCHAR(20),
    company_address VARCHAR(500),
    manager_name VARCHAR(255),
    home_address VARCHAR(500),
    total_area NUMERIC(8, 2),
    business_area NUMERIC(8, 2),
    landlord_name VARCHAR(255),
    landlord_address VARCHAR(500),
    tenant_name VARCHAR(255),
    tenant_address VARCHAR(500),
    rent_excl_charges NUMERIC(12, 2),
    charges_advance NUMERIC(12, 2),
    issue_place VARCHAR(255),
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE expense_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL,
    supplier VARCHAR(255),
    pro_rata_pct NUMERIC(5, 2) NOT NULL,
    periodicity VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL,
    multiple_lines_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_expense_item_prorata CHECK (pro_rata_pct >= 0 AND pro_rata_pct <= 100)
);

CREATE TABLE receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(120) NOT NULL,
    file_path VARCHAR(1000) NOT NULL,
    file_size BIGINT NOT NULL,
    hash_sha256 VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE rent_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_month VARCHAR(7) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    rent_excl_charges NUMERIC(12, 2) NOT NULL,
    charges NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    payment_date DATE,
    issue_date DATE,
    version INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    template_id BIGINT,
    template_name VARCHAR(255),
    template_version INTEGER,
    pdf_path VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_rent_receipt_billing_month_version UNIQUE (billing_month, version)
);
CREATE INDEX ix_rent_receipt_billing_month ON rent_receipt (billing_month);
CREATE UNIQUE INDEX ux_rent_receipt_active ON rent_receipt (billing_month) WHERE status = 'ACTIVE';

CREATE TABLE expense_statement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_month VARCHAR(7) NOT NULL,
    statement_number VARCHAR(20) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    version INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    template_id BIGINT,
    template_name VARCHAR(255),
    template_version INTEGER,
    pdf_path VARCHAR(1000),
    full_pdf_path VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_expense_statement_billing_month_version UNIQUE (billing_month, version)
);
CREATE INDEX ix_expense_statement_billing_month ON expense_statement (billing_month);
CREATE UNIQUE INDEX ux_expense_statement_active ON expense_statement (billing_month) WHERE status = 'ACTIVE';

CREATE TABLE expense_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL REFERENCES expense_statement (id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES expense_item (id),
    amount_incl_vat NUMERIC(12, 2) NOT NULL,
    period_start DATE,
    period_end DATE,
    monthly_amount NUMERIC(12, 2) NOT NULL,
    pro_rata_pct NUMERIC(5, 2) NOT NULL,
    claimed_amount NUMERIC(12, 2) NOT NULL,
    receipt_id BIGINT REFERENCES receipt (id),
    amount_source VARCHAR(10) NOT NULL,
    ai_detected_amount NUMERIC(12, 2),
    ai_confidence VARCHAR(20),
    label_snapshot VARCHAR(255),
    supplier_snapshot VARCHAR(255),
    CONSTRAINT ck_expense_line_prorata CHECK (pro_rata_pct >= 0 AND pro_rata_pct <= 100),
    CONSTRAINT ck_expense_line_amounts CHECK (amount_incl_vat >= 0 AND monthly_amount >= 0 AND claimed_amount >= 0)
);
CREATE INDEX ix_expense_line_statement ON expense_line (statement_id);

CREATE TABLE document_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES receipt (id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL,
    model VARCHAR(255),
    duration_ms BIGINT,
    result_json TEXT,
    error_message TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_document_analysis_receipt ON document_analysis (receipt_id);

CREATE TABLE llm_config (
    id BIGINT PRIMARY KEY,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    provider VARCHAR(20) NOT NULL,
    url VARCHAR(500) NOT NULL,
    model VARCHAR(255),
    timeout_seconds INTEGER NOT NULL DEFAULT 120,
    temperature NUMERIC(3, 2) NOT NULL DEFAULT 0,
    num_ctx INTEGER NOT NULL DEFAULT 8192,
    pages_max INTEGER NOT NULL DEFAULT 5,
    ocr_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    extraction_prompt TEXT NOT NULL,
    api_key TEXT,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE template_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    version INTEGER NOT NULL,
    format VARCHAR(10) NOT NULL,
    file_path VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    built_in BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    validation_report TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_template_type ON template_document (type);
CREATE UNIQUE INDEX ux_template_active ON template_document (type) WHERE active AND NOT deleted;
