-- Multi-company model: a company owns its expense items and statements, employees
-- carry a descriptive title, signatures attach to an employee and a lease may link to
-- a company. Existing data is migrated into company 1; the former settings row is
-- preserved as settings_legacy for one task as a rollback aid.

CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    legal_form VARCHAR(100),
    siren VARCHAR(20),
    address VARCHAR(500),
    manager_name VARCHAR(255),
    home_address VARCHAR(500),
    total_area NUMERIC(8, 2),
    business_area NUMERIC(8, 2),
    issue_place VARCHAR(255),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_company_deleted_name ON company (deleted, name);

INSERT INTO company (id, name, legal_form, siren, address, manager_name, home_address, total_area,
    business_area, issue_place, deleted, created_at, updated_at)
SELECT 1, COALESCE(NULLIF(company_name, ''), 'Société principale'), legal_form, siren,
       company_address, manager_name, home_address, total_area, business_area, issue_place,
       FALSE, COALESCE(updated_at, NOW()), updated_at
FROM settings
WHERE id = 1;

-- A fresh database without the legacy row still needs a company for the seed data.
INSERT INTO company (id, name, deleted, created_at)
SELECT 1, 'Société principale', FALSE, NOW()
WHERE NOT EXISTS (SELECT 1 FROM company WHERE id = 1);

SELECT setval(pg_get_serial_sequence('company', 'id'), (SELECT MAX(id) FROM company));

CREATE TABLE employee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company (id),
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    title VARCHAR(20) NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_employee_company_deleted ON employee (company_id, deleted);
CREATE UNIQUE INDEX ux_employee_company_email
    ON employee (company_id, lower(email))
    WHERE email IS NOT NULL AND NOT deleted;

-- Seed one CEO employee from the legacy manager name for each migrated company profile.
INSERT INTO employee (company_id, first_name, last_name, title, deleted, created_at, updated_at)
SELECT 1, COALESCE(NULLIF(manager_name, ''), 'Gérant'), '', 'CEO', FALSE,
       COALESCE(updated_at, NOW()), updated_at
FROM settings
WHERE id = 1;

INSERT INTO employee (company_id, first_name, last_name, title, deleted, created_at)
SELECT 1, 'Gérant', '', 'CEO', FALSE, NOW()
WHERE NOT EXISTS (SELECT 1 FROM employee WHERE company_id = 1 AND NOT deleted);

ALTER TABLE signature ADD COLUMN company_id BIGINT REFERENCES company (id);
ALTER TABLE signature ADD COLUMN employee_id BIGINT REFERENCES employee (id);

-- Legacy ENTREPRISE_CEO signatures now belong to the seeded CEO employee.
UPDATE signature
SET employee_id = (SELECT id FROM employee WHERE company_id = 1 AND NOT deleted
                   ORDER BY id LIMIT 1)
WHERE type = 'ENTREPRISE_CEO'
  AND employee_id IS NULL;

UPDATE signature
SET company_id = (SELECT company_id FROM employee WHERE employee.id = signature.employee_id)
WHERE employee_id IS NOT NULL
  AND company_id IS NULL;

ALTER TABLE signature
    ADD CONSTRAINT ck_signature_owner CHECK (
        (type = 'LANDLORD' AND employee_id IS NULL)
        OR (type IN ('EMPLOYEE', 'ENTREPRISE_CEO') AND employee_id IS NOT NULL AND landlord_id IS NULL)
    );
CREATE INDEX ix_signature_company_employee_deleted ON signature (company_id, employee_id, deleted);

ALTER TABLE lease ADD COLUMN company_id BIGINT REFERENCES company (id);
UPDATE lease SET company_id = 1 WHERE company_id IS NULL;
CREATE INDEX ix_lease_company ON lease (company_id);

ALTER TABLE expense_item ADD COLUMN company_id BIGINT REFERENCES company (id);
UPDATE expense_item SET company_id = 1 WHERE company_id IS NULL;
ALTER TABLE expense_item ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE expense_item DROP CONSTRAINT expense_item_code_key;
ALTER TABLE expense_item ADD CONSTRAINT uq_expense_item_company_code UNIQUE (company_id, code);
CREATE INDEX ix_expense_item_company_deleted ON expense_item (company_id, deleted);

ALTER TABLE expense_statement ADD COLUMN company_id BIGINT REFERENCES company (id);
UPDATE expense_statement SET company_id = 1 WHERE company_id IS NULL;
ALTER TABLE expense_statement ALTER COLUMN company_id SET NOT NULL;
ALTER TABLE expense_statement DROP CONSTRAINT uq_expense_statement_billing_month_version;
DROP INDEX ux_expense_statement_active;
ALTER TABLE expense_statement
    ADD CONSTRAINT uq_expense_statement_company_month_version
    UNIQUE (company_id, billing_month, version);
CREATE UNIQUE INDEX ux_expense_statement_active
    ON expense_statement (company_id, billing_month)
    WHERE status = 'ACTIVE';
CREATE INDEX ix_expense_statement_company_month
    ON expense_statement (company_id, billing_month, version);
CREATE INDEX ix_expense_statement_company_status
    ON expense_statement (company_id, status);

ALTER TABLE rent_receipt ADD COLUMN company_id BIGINT REFERENCES company (id);
UPDATE rent_receipt receipt
SET company_id = COALESCE((
        SELECT lease.company_id FROM lease
        WHERE lease.landlord_id = receipt.landlord_id
          AND lease.tenant_id = receipt.tenant_id
          AND NOT lease.deleted
        ORDER BY lease.id LIMIT 1
    ), 1)
WHERE company_id IS NULL;
CREATE INDEX ix_rent_receipt_company_month ON rent_receipt (company_id, billing_month);

ALTER TABLE settings RENAME TO settings_legacy;
