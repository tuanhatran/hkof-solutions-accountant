CREATE TABLE landlord (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(500),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_landlord_deleted_name ON landlord (deleted, name);

CREATE TABLE tenant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(500),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_tenant_deleted_name ON tenant (deleted, name);

CREATE TABLE lease (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landlord_id BIGINT NOT NULL REFERENCES landlord (id),
    tenant_id BIGINT NOT NULL REFERENCES tenant (id),
    property_address VARCHAR(500) NOT NULL,
    rent_excl_charges NUMERIC(12, 2) NOT NULL,
    charges NUMERIC(12, 2) NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_lease_landlord_tenant ON lease (landlord_id, tenant_id);
-- One active lease per landlord and tenant pair: logical deletion frees the pair.
CREATE UNIQUE INDEX ux_lease_active_pair ON lease (landlord_id, tenant_id) WHERE NOT deleted;

-- Migrate the single settings row (id = 1) into one landlord, one tenant and one lease.
INSERT INTO landlord (name, address, deleted, created_at)
SELECT COALESCE(landlord_name, ''), landlord_address, FALSE, COALESCE(updated_at, NOW())
FROM settings
WHERE id = 1;

INSERT INTO tenant (name, address, deleted, created_at)
SELECT COALESCE(tenant_name, ''), tenant_address, FALSE, COALESCE(updated_at, NOW())
FROM settings
WHERE id = 1;

INSERT INTO lease (landlord_id, tenant_id, property_address, rent_excl_charges, charges, deleted, created_at)
SELECT (SELECT id FROM landlord ORDER BY id LIMIT 1),
       (SELECT id FROM tenant ORDER BY id LIMIT 1),
       COALESCE(home_address, ''),
       COALESCE(rent_excl_charges, 0),
       COALESCE(charges_advance, 0),
       FALSE,
       COALESCE(updated_at, NOW())
FROM settings
WHERE id = 1
  AND EXISTS (SELECT 1 FROM landlord)
  AND EXISTS (SELECT 1 FROM tenant);

ALTER TABLE rent_receipt ADD COLUMN landlord_id BIGINT REFERENCES landlord (id);
ALTER TABLE rent_receipt ADD COLUMN tenant_id BIGINT REFERENCES tenant (id);

UPDATE rent_receipt
SET landlord_id = (SELECT id FROM landlord ORDER BY id LIMIT 1),
    tenant_id = (SELECT id FROM tenant ORDER BY id LIMIT 1)
WHERE landlord_id IS NULL
  AND tenant_id IS NULL
  AND EXISTS (SELECT 1 FROM landlord)
  AND EXISTS (SELECT 1 FROM tenant);

CREATE INDEX ix_rent_receipt_landlord_tenant ON rent_receipt (landlord_id, tenant_id);

-- The landlord, tenant and home/rent values now live in the lease; keep the settings table
-- focused on the company, the pro-rata areas and the issue place.
ALTER TABLE settings
    DROP COLUMN landlord_name,
    DROP COLUMN landlord_address,
    DROP COLUMN tenant_name,
    DROP COLUMN tenant_address,
    DROP COLUMN rent_excl_charges,
    DROP COLUMN charges_advance;
