-- Every template document and LLM configuration belongs to one account.
-- Existing rows are backfilled to the seeded thtran account.

ALTER TABLE template_document ADD COLUMN user_id BIGINT REFERENCES app_user (id);
ALTER TABLE llm_config ADD COLUMN user_id BIGINT REFERENCES app_user (id);

UPDATE template_document
SET user_id = (SELECT id FROM app_user WHERE lower(email) = 'thtran@homeofficeexpenses.local' ORDER BY id LIMIT 1)
WHERE user_id IS NULL;

UPDATE llm_config
SET user_id = (SELECT id FROM app_user WHERE lower(email) = 'thtran@homeofficeexpenses.local' ORDER BY id LIMIT 1)
WHERE user_id IS NULL;

ALTER TABLE template_document ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE llm_config ALTER COLUMN user_id SET NOT NULL;

DROP INDEX IF EXISTS ux_template_active;
CREATE UNIQUE INDEX ux_template_user_active ON template_document (user_id, type) WHERE active AND NOT deleted;
CREATE INDEX ix_template_user_type ON template_document (user_id, type, deleted);

ALTER TABLE llm_config ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('llm_config', 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM llm_config), 1), (SELECT COUNT(*) > 0 FROM llm_config));

CREATE UNIQUE INDEX ux_llm_config_user ON llm_config (user_id);
