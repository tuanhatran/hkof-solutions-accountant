CREATE TABLE agency (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user (id),
    name VARCHAR(255) NOT NULL,
    is_personal BOOLEAN NOT NULL DEFAULT FALSE,
    manager_name VARCHAR(255),
    legal_form VARCHAR(100),
    siren VARCHAR(9),
    siret VARCHAR(14),
    address VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX ux_agency_user_id ON agency (user_id);

-- Backfill agency for existing users who already completed onboarding
INSERT INTO agency (user_id, name, is_personal, manager_name, legal_form, siren, siret, address, created_at)
SELECT u.id,
       COALESCE(c.name, 'Agence ' || COALESCE(p.name, u.email)),
       FALSE,
       COALESCE(c.manager_name, p.name),
       c.legal_form,
       c.siren,
       c.siret,
       c.address,
       CURRENT_TIMESTAMP
FROM app_user u
LEFT JOIN (
    SELECT DISTINCT ON (user_id) user_id, name, manager_name, legal_form, siren, siret, address
    FROM company
    WHERE deleted = FALSE
    ORDER BY user_id, id ASC
) c ON c.user_id = u.id
LEFT JOIN (
    SELECT DISTINCT ON (user_id) user_id, name
    FROM person
    WHERE deleted = FALSE
    ORDER BY user_id, id ASC
) p ON p.user_id = u.id
WHERE u.onboarding_completed = TRUE
ON CONFLICT (user_id) DO NOTHING;
