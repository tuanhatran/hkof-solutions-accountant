-- A lease may carry several natural-person tenants. The legacy lease.tenant_id column stays the
-- primary tenant and is backfilled into the join table with is_primary = TRUE, so existing
-- receipts and services keep their reference. A person is attached at most once per lease.
CREATE TABLE lease_tenant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_id BIGINT NOT NULL REFERENCES lease (id),
    person_id BIGINT NOT NULL REFERENCES person (id),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX ux_lease_tenant_pair ON lease_tenant (lease_id, person_id);
CREATE INDEX ix_lease_tenant_person ON lease_tenant (person_id, lease_id);

INSERT INTO lease_tenant (lease_id, person_id, is_primary)
SELECT id, tenant_id, TRUE FROM lease WHERE tenant_id IS NOT NULL;

-- Onboarding profile: contact details and the company legal establishment identifier.
ALTER TABLE person ADD COLUMN phone VARCHAR(50);
ALTER TABLE person ADD COLUMN address_note VARCHAR(500);
ALTER TABLE company ADD COLUMN siret VARCHAR(20);

-- Existing accounts already live with their data: they must never be redirected to onboarding.
-- Accounts created after this migration keep the default and go through the wizard.
ALTER TABLE app_user ADD COLUMN onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE app_user SET onboarding_completed = TRUE;

-- Lease-tenant uniqueness now lives in the join table; the active-pair index on lease would
-- block a second tenant on the same lease.
DROP INDEX IF EXISTS ux_lease_user_active_pair;
