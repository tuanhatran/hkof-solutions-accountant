-- An address becomes a first-class entity: one address carries any number of leases.
-- Existing property labels are deduplicated (trimmed, case-insensitive) and every lease,
-- logically deleted ones included, is linked before the legacy column is dropped.

CREATE TABLE address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(500) NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX ux_address_label_active ON address (lower(label)) WHERE NOT deleted;

INSERT INTO address (label, deleted, created_at)
SELECT DISTINCT ON (lower(btrim(property_address))) btrim(property_address), FALSE, NOW()
FROM lease
ORDER BY lower(btrim(property_address)), btrim(property_address);

ALTER TABLE lease ADD COLUMN address_id BIGINT;
UPDATE lease l
SET address_id = a.id
FROM address a
WHERE lower(a.label) = lower(btrim(l.property_address));
ALTER TABLE lease ALTER COLUMN address_id SET NOT NULL;
ALTER TABLE lease ADD CONSTRAINT fk_lease_address FOREIGN KEY (address_id) REFERENCES address (id);
CREATE INDEX ix_lease_address ON lease (address_id);

ALTER TABLE lease DROP COLUMN property_address;
