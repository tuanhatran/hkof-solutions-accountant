-- Merge landlord, tenant and employee into one person table (kind PERSON or EMPLOYEE),
-- attach signatures to a person, make the tenant of a company lease a company, and keep
-- every lease, receipt and signature addressable.

ALTER TABLE lease DROP CONSTRAINT IF EXISTS lease_landlord_id_fkey;
ALTER TABLE lease DROP CONSTRAINT IF EXISTS lease_tenant_id_fkey;
ALTER TABLE lease ALTER COLUMN tenant_id DROP NOT NULL;
ALTER TABLE rent_receipt DROP CONSTRAINT IF EXISTS rent_receipt_landlord_id_fkey;
ALTER TABLE rent_receipt DROP CONSTRAINT IF EXISTS rent_receipt_tenant_id_fkey;
ALTER TABLE rent_receipt ALTER COLUMN tenant_id DROP NOT NULL;
ALTER TABLE signature DROP CONSTRAINT IF EXISTS signature_landlord_id_fkey;
ALTER TABLE signature DROP CONSTRAINT IF EXISTS signature_employee_id_fkey;
ALTER TABLE signature DROP CONSTRAINT IF EXISTS signature_company_id_fkey;

CREATE TABLE person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    name VARCHAR(255),
    address VARCHAR(500),
    company_id BIGINT REFERENCES company (id),
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    email VARCHAR(255),
    title VARCHAR(20),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE
);

-- One fresh identifier space for every kind: old identifiers overlap, so tenants and
-- employees are shifted into ranges that cannot collide with preserved landlord ids.
CREATE TEMP TABLE person_offsets AS
SELECT GREATEST(
    (SELECT COALESCE(MAX(id), 0) FROM landlord),
    (SELECT COALESCE(MAX(id), 0) FROM tenant),
    (SELECT COALESCE(MAX(id), 0) FROM employee)
) + 1 AS next_id;

INSERT INTO person (id, kind, name, address, deleted, created_at)
SELECT id, 'PERSON', name, address, deleted, created_at FROM landlord ORDER BY id;

INSERT INTO person (id, kind, name, address, deleted, created_at)
SELECT id + (SELECT next_id FROM person_offsets), 'PERSON', name, address, deleted, created_at
FROM tenant ORDER BY id;

INSERT INTO person (id, kind, company_id, first_name, last_name, email, title, deleted, created_at, updated_at)
SELECT id + 2 * (SELECT next_id FROM person_offsets), 'EMPLOYEE', company_id, first_name, last_name,
       email, title, deleted, created_at, updated_at
FROM employee ORDER BY id;

-- Receipts of an enterprise lease move their tenant to the tenant company.
ALTER TABLE rent_receipt ADD COLUMN tenant_company_id BIGINT;

UPDATE rent_receipt receipt
SET tenant_company_id = lease.company_id
FROM lease
WHERE lease.landlord_id = receipt.landlord_id
  AND lease.tenant_id = receipt.tenant_id
  AND lease.company_lease
  AND lease.company_id IS NOT NULL
  AND NOT lease.deleted;

UPDATE rent_receipt SET tenant_id = NULL WHERE tenant_company_id IS NOT NULL;
UPDATE rent_receipt
SET tenant_id = tenant_id + (SELECT next_id FROM person_offsets)
WHERE tenant_id IS NOT NULL;

-- Lease tenants are remapped, then enterprise leases drop their natural-person tenant.
UPDATE lease
SET tenant_id = tenant_id + (SELECT next_id FROM person_offsets)
WHERE tenant_id IS NOT NULL;
UPDATE lease SET company_lease = FALSE WHERE company_lease AND company_id IS NULL;
UPDATE lease SET tenant_id = NULL WHERE company_lease;

ALTER TABLE signature ADD COLUMN person_id BIGINT;
UPDATE signature
SET person_id = CASE
    WHEN type = 'LANDLORD' AND landlord_id IS NOT NULL THEN landlord_id
    WHEN type IN ('EMPLOYEE', 'ENTREPRISE_CEO') AND employee_id IS NOT NULL
        THEN employee_id + 2 * (SELECT next_id FROM person_offsets)
    ELSE NULL
END;
-- Legacy unlinked landlord signatures attach only when the choice is unambiguous; otherwise
-- they are logically deleted, never physically removed.
UPDATE signature
SET person_id = (
    SELECT id FROM person
    WHERE kind = 'PERSON' AND NOT deleted
    ORDER BY id LIMIT 1
)
WHERE type = 'LANDLORD'
  AND landlord_id IS NULL
  AND person_id IS NULL
  AND (SELECT COUNT(*) FROM person WHERE kind = 'PERSON' AND NOT deleted) = 1;
UPDATE signature SET deleted = TRUE WHERE person_id IS NULL;

ALTER TABLE signature DROP CONSTRAINT IF EXISTS ck_signature_owner;
DROP INDEX IF EXISTS ix_signature_deleted_type;
DROP INDEX IF EXISTS ix_signature_landlord;
DROP INDEX IF EXISTS ix_signature_company_employee_deleted;
ALTER TABLE signature
    DROP COLUMN type,
    DROP COLUMN landlord_id,
    DROP COLUMN company_id,
    DROP COLUMN employee_id;
ALTER TABLE signature ADD CONSTRAINT fk_signature_person FOREIGN KEY (person_id) REFERENCES person (id);
CREATE INDEX ix_signature_person_deleted ON signature (person_id, deleted);
ALTER TABLE signature ADD CONSTRAINT ck_signature_person CHECK (person_id IS NOT NULL OR deleted);

ALTER TABLE lease
    ADD CONSTRAINT fk_lease_landlord FOREIGN KEY (landlord_id) REFERENCES person (id);
ALTER TABLE lease
    ADD CONSTRAINT fk_lease_tenant FOREIGN KEY (tenant_id) REFERENCES person (id);
DROP INDEX IF EXISTS ux_lease_active_pair;
CREATE UNIQUE INDEX ux_lease_active_pair ON lease (landlord_id, tenant_id)
    WHERE NOT deleted AND NOT company_lease;
CREATE UNIQUE INDEX ux_lease_active_company ON lease (landlord_id, company_id)
    WHERE NOT deleted AND company_lease;
ALTER TABLE lease ADD CONSTRAINT ck_lease_parties CHECK (
    (company_lease AND tenant_id IS NULL AND company_id IS NOT NULL)
    OR ((NOT company_lease) AND tenant_id IS NOT NULL)
);

ALTER TABLE rent_receipt
    ADD CONSTRAINT fk_rent_receipt_landlord FOREIGN KEY (landlord_id) REFERENCES person (id);
ALTER TABLE rent_receipt
    ADD CONSTRAINT fk_rent_receipt_tenant FOREIGN KEY (tenant_id) REFERENCES person (id);
ALTER TABLE rent_receipt
    ADD CONSTRAINT fk_rent_receipt_tenant_company FOREIGN KEY (tenant_company_id) REFERENCES company (id);
ALTER TABLE rent_receipt ADD CONSTRAINT ck_rent_receipt_tenant CHECK (
    tenant_id IS NULL OR tenant_company_id IS NULL
);
DROP INDEX IF EXISTS uq_rent_receipt_month_pair_version;
CREATE UNIQUE INDEX uq_rent_receipt_month_tenant_version ON rent_receipt (
    billing_month,
    landlord_id,
    COALESCE(tenant_id, 0),
    COALESCE(tenant_company_id, 0),
    version
);

CREATE INDEX ix_person_kind_deleted_name ON person (kind, deleted, name);
CREATE INDEX ix_person_company_deleted ON person (company_id, deleted);
CREATE UNIQUE INDEX ux_person_company_email ON person (company_id, lower(email))
    WHERE kind = 'EMPLOYEE' AND email IS NOT NULL AND NOT deleted;
ALTER TABLE person ADD CONSTRAINT ck_person_kind CHECK (
    (kind = 'PERSON' AND name IS NOT NULL AND company_id IS NULL AND first_name IS NULL
        AND last_name IS NULL AND email IS NULL AND title IS NULL)
    OR (kind = 'EMPLOYEE' AND name IS NULL AND company_id IS NOT NULL AND first_name IS NOT NULL
        AND last_name IS NOT NULL AND title IS NOT NULL)
);

DROP TABLE landlord;
DROP TABLE tenant;
DROP TABLE employee;

SELECT setval(
    pg_get_serial_sequence('person', 'id'),
    COALESCE((SELECT MAX(id) FROM person), 1),
    (SELECT MAX(id) FROM person) IS NOT NULL
);
